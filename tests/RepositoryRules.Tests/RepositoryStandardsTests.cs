using System.Xml.Linq;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Xunit;

namespace RepositoryRules.Tests;

public class RepositoryStandardsTests
{
    [Theory]
    [InlineData("class Example { private int value; }", true)]
    [InlineData("class Example { private const int Value = 1; }", true)]
    [InlineData("class Example { static readonly int value = 1; }", true)]
    [InlineData("class Example { int _Value; }", true)]
    [InlineData("class Example { int _; }", true)]
    [InlineData("class Example { int __value; }", true)]
    [InlineData("class Example { int _value; }", false)]
    [InlineData("class Example { private const int _value = 1; }", false)]
    [InlineData("class Example { public int Value; }", false)]
    [InlineData("class Example { protected int Value; }", false)]
    [InlineData("class Example {} interface IExample {}", true)]
    [InlineData("class Example { class Helper {} }", true)]
    [InlineData("record Example(); delegate void Callback();", true)]
    [InlineData("partial class Example {}", false)]
    [InlineData("// <auto-generated/>\nclass Example { int value; } class Other {}", true)]
    [InlineData("interface IExample { private const int Value = 1; }", true)]
    [InlineData("interface IExample { const int Value = 1; }", false)]
    public void SyntaxRulesRejectViolations(string source, bool invalid)
    {
        Assert.Equal(invalid, CSharpRules.Check(source, "fixture.cs").Count > 0);
    }

    [Fact]
    public void GeneratedFilesNeedBothAnExpectedPathAndBanner()
    {
        const string source = "// <auto-generated/>\nclass Example { int value; } class Other {}";
        Assert.Empty(CSharpRules.Check(source, "fixture.g.cs"));
        Assert.NotEmpty(CSharpRules.Check(source, "fixture.cs"));
        Assert.NotEmpty(CSharpRules.Check("class Example { int value; }", "fixture.g.cs"));
    }

    [Fact]
    public void ConditionalAndRazorFieldsAreChecked()
    {
        const string source = "class Example {\n#if DEBUG\nint invalid;\n#else\nint _valid;\n#endif\n}";
        Assert.Empty(CSharpRules.Check(source, "fixture.cs"));
        Assert.NotEmpty(CSharpRules.Check(source, "fixture.cs", "DEBUG"));
        Assert.NotEmpty(CSharpRules.CheckRazor("<p>View</p>\n@code { int invalid; }", "view.razor"));
        Assert.Empty(CSharpRules.CheckRazor("@code { int _valid; }", "view.razor"));
    }

    [Fact]
    public void HandwrittenSourcesFollowStandards()
    {
        var root = FindRoot();
        var errors = new List<string>();
        foreach (var folder in new[] { "src", "tests" })
        {
            foreach (var path in EnumerateFiles(Path.Combine(root, folder))
                .Where(path => Path.GetExtension(path) is ".cs" or ".razor"))
            {
                var source = File.ReadAllText(path);
                var relative = Path.GetRelativePath(root, path);
                if (path.EndsWith(".razor", StringComparison.Ordinal))
                    errors.AddRange(CSharpRules.CheckRazor(source, relative));
                else
                {
                    errors.AddRange(CSharpRules.Check(source, relative));
                    errors.AddRange(CSharpRules.Check(source, relative, "DEBUG"));
                }
            }
        }
        Assert.True(errors.Count == 0, string.Join(Environment.NewLine, errors.Distinct()));
    }

    [Fact]
    public void InstructionAndSkillEntrypointsResolveForAllThreeHosts()
    {
        var root = FindRoot();
        foreach (var folder in new[] { "", "src/dotnetliguriawebsite", "src/dotnetliguriaspa", "src/BlazorQuestionario", "src/BlazorQuestionarioServer", "tests" })
            Assert.True(File.Exists(Path.Combine(root, folder, "AGENTS.md")), $"Missing guidance in {folder}");
        Assert.Contains("@AGENTS.md", File.ReadAllText(Path.Combine(root, "CLAUDE.md")));
        Assert.Contains("../AGENTS.md", File.ReadAllText(Path.Combine(root, ".github/copilot-instructions.md")));
        foreach (var skill in new[] { "fast-verification", "dependency-modernization" })
        {
            var canonical = Path.Combine(root, ".agents", "skills", skill, "SKILL.md");
            Assert.Contains($"name: {skill}", File.ReadAllText(canonical));
            foreach (var host in new[] { ".claude", ".github" })
            {
                var adapter = Path.Combine(root, host, "skills", skill, "SKILL.md");
                var target = $"../../../.agents/skills/{skill}/SKILL.md";
                Assert.Contains(target, File.ReadAllText(adapter));
                Assert.Equal(Path.GetFullPath(canonical), Path.GetFullPath(Path.Combine(Path.GetDirectoryName(adapter)!, target)));
            }
        }
    }

    [Fact]
    public void BothExecutablesConfigureBsonBeforeHostOrMigrationWork()
    {
        var root = FindRoot();
        foreach (var (path, nextCall) in new[]
        {
            ("src/dotnetliguriawebsite/DotNetLiguriaCore/Program.cs", "WebApplication.CreateBuilder"),
            ("src/dotnetliguriawebsite/DataMigration/Program.cs", "ConfigurationReader.Read")
        })
        {
            var syntax = CSharpSyntaxTree.ParseText(File.ReadAllText(Path.Combine(root, path))).GetRoot();
            var calls = syntax.DescendantNodes().OfType<InvocationExpressionSyntax>().ToList();
            var configure = Assert.Single(calls, call => call.Expression.ToString().EndsWith("BsonCompatibility.Configure", StringComparison.Ordinal));
            var next = calls.First(call => call.Expression.ToString().StartsWith(nextCall, StringComparison.Ordinal));
            Assert.True(configure.SpanStart < next.SpanStart, $"BSON configuration is too late in {path}");
        }
    }

    [Fact]
    public void EveryProjectTargetsNet10()
    {
        var root = FindRoot();
        foreach (var path in EnumerateFiles(root).Where(path => path.EndsWith(".csproj", StringComparison.Ordinal)))
        {
            var project = XDocument.Load(path);
            Assert.Equal("net10.0", project.Descendants("TargetFramework").Single().Value);
            Assert.DoesNotContain(project.Descendants("PackageReference"), reference => reference.Attribute("Version")?.Value.Contains('-') == true);
        }
    }

    private static IEnumerable<string> EnumerateFiles(string folder)
    {
        foreach (var path in Directory.EnumerateFiles(folder))
            yield return path;
        foreach (var directory in Directory.EnumerateDirectories(folder))
        {
            if (Path.GetFileName(directory) is "obj" or "bin" or "node_modules" or ".git" or ".artifacts" or "dist"
                || (File.GetAttributes(directory) & FileAttributes.ReparsePoint) != 0)
                continue;
            foreach (var path in EnumerateFiles(directory))
                yield return path;
        }
    }

    private static string FindRoot()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null && !File.Exists(Path.Combine(directory.FullName, "global.json")))
            directory = directory.Parent;
        return directory?.FullName ?? throw new InvalidOperationException("Repository root not found");
    }
}