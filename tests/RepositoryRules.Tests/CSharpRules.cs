using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace RepositoryRules.Tests;

public static class CSharpRules
{
    public static List<string> Check(string source, string path, params string[] symbols)
    {
        var root = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(preprocessorSymbols: symbols)).GetRoot();
        var generatedPath = path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".Designer.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith("ModelSnapshot.cs", StringComparison.OrdinalIgnoreCase);
        if (generatedPath && root.GetLeadingTrivia().ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
            return [];

        var declarations = root.DescendantNodes().Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax).ToList();
        var errors = new List<string>();
        if (declarations.Count > 1)
            errors.Add($"{path}: declares {declarations.Count} types; each handwritten type needs its own file");

        foreach (var field in root.DescendantNodes().OfType<FieldDeclarationSyntax>())
        {
            var hasAccessibility = field.Modifiers.Any(token => token.IsKind(SyntaxKind.PublicKeyword)
                || token.IsKind(SyntaxKind.InternalKeyword) || token.IsKind(SyntaxKind.ProtectedKeyword));
            if (hasAccessibility || (field.Parent is InterfaceDeclarationSyntax
                && !field.Modifiers.Any(SyntaxKind.PrivateKeyword)))
                continue;
            foreach (var variable in field.Declaration.Variables)
            {
                var name = variable.Identifier.ValueText;
                if (name.Length < 2 || name[0] != '_' || !char.IsLower(name[1]) || name[1..].Contains('_'))
                    errors.Add($"{path}:{variable.GetLocation().GetLineSpan().StartLinePosition.Line + 1}: private field '{name}' must be _camelCase");
            }
        }
        return errors;
    }

    public static IEnumerable<string> CheckRazor(string source, string path)
    {
        foreach (var marker in new[] { "@code", "@functions" })
        {
            var offset = 0;
            while ((offset = source.IndexOf(marker, offset, StringComparison.Ordinal)) >= 0)
            {
                var body = source[(offset + marker.Length)..].TrimStart();
                var declaration = SyntaxFactory.ParseMemberDeclaration("class RazorComponent " + body, consumeFullText: false);
                if (declaration is not ClassDeclarationSyntax component)
                    throw new InvalidOperationException($"Cannot parse handwritten C# in {path}");
                foreach (var error in Check(component.ToFullString(), path))
                    yield return error;
                offset += marker.Length;
            }
        }
    }
}